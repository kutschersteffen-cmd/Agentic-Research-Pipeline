"""The `simulated_esg` schema: the 25 non-climate fields of the simulated dataset (`data/simulated/esg_simulated.csv`),
as `arp showcase load` writes them. SIMULATED DATA: no field here is a real company's real data."""

from __future__ import annotations

from arp.schemas.datapoints import DataPointSchema, FieldDataType, FieldDefinition
from arp.showcase.simulate import ACTIVITIES, GRADES

SIMULATED_SCHEMA_ID = "simulated_esg"
_N, _B, _S, _E = FieldDataType.NUMBER, FieldDataType.BOOLEAN, FieldDataType.STRING, FieldDataType.ENUM
_LCT = ["solutions", "asset_stranding", "operational_transition", "product_transition", "neutral"]

# field id (a dataset column, except peer_group = the `sector` column), name, type, unit, allowed values
_FIELDS = [
    ("esg_e_score", "Environmental score", _N, "0 to 10", None),
    ("esg_s_score", "Social score", _N, "0 to 10", None),
    ("esg_g_score", "Governance score", _N, "0 to 10", None),
    ("esg_score", "ESG score", _N, "0 to 10", None),
    ("esg_trend", "ESG trend", _N, "ratio, 0.80 to 1.20", None),
    ("controversy_level", "Controversy level", _N, "0 to 5", None),
    *((f"{a}_revenue_pct", f"{a.replace('_', ' ').capitalize()} revenue share", _N, "fraction of revenue", None) for a in ACTIVITIES),
    ("controversial_weapons", "Controversial weapons", _B, None, None),
    ("norms_violation", "Norms violation", _B, None, None),
    ("severe_controversy", "Severe controversy", _B, None, None),
    ("ghg_intensity", "GHG intensity", _N, "tCO2e / EUR M revenue", None),
    ("green_revenue_pct", "Green revenue share", _N, "fraction of revenue", None),
    ("transition_score", "Transition score", _N, "0 to 1", None),
    ("lct_score", "Low-carbon transition score", _N, "0 to 10", None),
    ("lct_category", "Low-carbon transition category", _E, None, _LCT),
    ("transition_grade", "Transition grade", _E, None, [g[0] for g in GRADES]),
    ("transition_grade_label", "Transition grade label", _E, None, [g[1] for g in GRADES]),
    ("peer_group", "Peer group", _S, None, None),
]
FIELD_IDS = [f[0] for f in _FIELDS]


def build_simulated_schema() -> DataPointSchema:
    return DataPointSchema(
        schema_id=SIMULATED_SCHEMA_ID,
        name="Simulated ESG",
        description="SIMULATED DATA. Not real ESG data. Generated by arp showcase simulate.",
        fields=[
            FieldDefinition(
                field_id=fid, name=name, data_type=data_type, unit=unit, allowed_values=allowed,
                description=f"Simulated: {name.lower()} of the simulated ESG dataset, a sector-based estimate.",
                extraction_instructions="Not extracted. Loaded from data/simulated/esg_simulated.csv by arp showcase load.",
                required=False,
            )
            for fid, name, data_type, unit, allowed in _FIELDS
        ],
    )
